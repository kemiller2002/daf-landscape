let money (x: float) =
    if System.Double.IsInfinity x then "never"
    elif abs x >= 1.0e9 then (x / 1.0e9).ToString("0.00", CultureInfo.InvariantCulture) + "B"
    elif abs x >= 1.0e6 then (x / 1.0e6).ToString("0.00", CultureInfo.InvariantCulture) + "M"
    elif abs x >= 1.0e3 then (x / 1.0e3).ToString("0.0", CultureInfo.InvariantCulture) + "k"
    else x.ToString("0.00", CultureInfo.InvariantCulture)

let n2 (x: float) = if System.Double.IsInfinity x then "never" else x.ToString("0.00", CultureInfo.InvariantCulture)
let pct (x: float) = (x * 100.0).ToString("0.0", CultureInfo.InvariantCulture) + "%"
let opt = function Some x -> fmt x | None -> "never"

let table (header: string list) (rows: string list list) =
    let line cells = "| " + String.concat " | " cells + " |"
    (line header :: line (header |> List.map (fun _ -> "---")) :: (rows |> List.map line)) |> String.concat "\n"

let eventCostsCsv (inputs: Inputs) (vals: Values) =
    let header = [ "mode_id"; "event_id"; "event"; "frequency_per_acct"; "touch_prob"; "minutes_per_touch"; "human_min_per_acct"; "labour_per_acct"; "vendor_external_per_acct"; "pass_through_per_acct"; "ai_per_acct"; "prevention_per_acct"; "expected_failure_per_acct"; "success_cost_per_event"; "failure_lifecycle_cost"; "sponsor_level_minutes"; "onetime_cost" ]
    let rows =
        [ for m in inputs.Modes do
            for c in costs m vals inputs.Events do
                yield [ m.Id; c.EventId; c.Name; fmt c.Frequency; fmt c.TouchProb; fmt c.MinutesPerTouch; fmt c.HumanMinutesPerAcct; fmt c.LabourPerAcct
                        fmt c.VendorExternalPerAcct; fmt c.PassThroughPerAcct; fmt c.AiPerAcct; fmt c.PreventionPerAcct; fmt c.ExpectedFailurePerAcct
                        fmt c.SuccessCostPerEvent; fmt c.FailureLifecycleCost; fmt c.SponsorLevelMinutes; fmt c.OnetimeCost ] ]
    write header rows

let modeSummaryRows (inputs: Inputs) (vals: Values) =
    allEconomics inputs vals
    |> List.map (fun m ->
        [ m.Mode.Id; m.Mode.Name; fmt m.HumanMinutesPerAcct; fmt m.VendorVariablePerAcct; fmt m.SystemVariablePerAcct
          fmt m.SystemSponsorLevelCost; fmt m.VendorFixed; fmt m.Build; fmt m.OnetimePerSponsor; fmt m.OnetimePerAcct
          fmt (systemCostPerAccount 10000.0 5.0 m); fmt (systemCostPerAccount 40000.0 5.0 m) ])

let modeSummaryHeader = [ "mode_id"; "mode"; "human_min_per_acct"; "vendor_variable_per_acct"; "system_variable_per_acct"; "sponsor_level_cost_per_sponsor"; "vendor_fixed"; "build"; "onetime_per_sponsor"; "onetime_per_acct"; "system_cost_per_acct_10k_accts_5_sponsors"; "system_cost_per_acct_40k_accts_5_sponsors" ]

let breakEvenCsv (rows: BreakEvenRow list) (mc: McRow list) (mcc: McRow list) =
    let header = [ "mode_id"; "bps"; "avg_balance"; "break_even_assets_base"; "break_even_fully_loaded"; "mc_p10"; "mc_p50"; "mc_p90"; "mc_never_share"; "mc_corr_p10"; "mc_corr_p50"; "mc_corr_p90"; "mc_corr_never_share" ]
    write header
        (rows |> List.map (fun r ->
            let m = mc |> List.find (fun x -> x.ModeId = r.ModeId && x.Bps = r.Bps)
            let c = mcc |> List.find (fun x -> x.ModeId = r.ModeId && x.Bps = r.Bps)
            [ r.ModeId; fmt r.Bps; fmt r.Balance; opt r.Assets; opt r.Loaded; fmt m.P10; fmt m.P50; fmt m.P90; fmt m.NeverShare; fmt c.P10; fmt c.P50; fmt c.P90; fmt c.NeverShare ]))

let resultsMarkdown (inputs: Inputs) (vals: Values) (be: BreakEvenRow list) (mc: McRow list) (mcc: McRow list) (st: StressRow list) (dec: Decomposition list)
                    (prev: PreventionRow list) (tor: TornadoRow list) (par1: ParetoRow list) (par5: ParetoRow list)
                    (regRecon: (RegistryComponent * float) list * float) (regBase: (string * Registry.RegistryCost) list)
                    (regMc: (string * (float * float * float)) list) (lowest: RegistryRow list)
                    (routes: RouteRow list) (routeMc: RouteMcRow list) =
    let sections =
        [ "# Competitive displacement model results"
          ""
          "Generated by `model/src/CompetitiveDisplacement` from `data/model-inputs/`. Every figure is conditional on labelled inputs (ASSUMPTION/INFERENCE). Monte Carlo: 2,000 seeded triangular draws, independent parameters (ASSUMPTION). Re-run produces byte-identical output."
          ""
          "## 1. Operating modes (base values, 5 sponsors)"
          ""
          table [ "Mode"; "Human min/acct-yr"; "Vendor variable $/acct"; "System variable $/acct"; "Sponsor-level $/sponsor-yr"; "Vendor fixed"; "Build"; "System $/acct @10k accts"; "System $/acct @40k accts" ]
              (allEconomics inputs vals |> List.map (fun m ->
                  [ m.Mode.Id + " " + m.Mode.Name; n2 m.HumanMinutesPerAcct; n2 m.VendorVariablePerAcct; n2 m.SystemVariablePerAcct; money m.SystemSponsorLevelCost
                    money m.VendorFixed; money m.Build; n2 (systemCostPerAccount 10000.0 5.0 m); n2 (systemCostPerAccount 40000.0 5.0 m) ]))
          ""
          "## 2. Break-even average billable assets (base; $250k balance; 5 sponsors)"
          ""
          table ("Mode" :: (bpsGrid |> List.map (fun b -> fmt b + " bps")))
              (inputs.Modes |> List.map (fun m ->
                  m.Id :: (bpsGrid |> List.map (fun b -> be |> List.find (fun r -> r.ModeId = m.Id && r.Bps = b && r.Balance = 250000.0) |> fun r -> r.Assets |> Option.map money |> Option.defaultValue "never"))))
          ""
          "## 2a. Fully loaded break-even (build, CAC and onboarding amortised; $250k balance; 5 sponsors)"
          ""
          table ("Mode" :: (bpsGrid |> List.map (fun b -> fmt b + " bps")))
              (inputs.Modes |> List.map (fun m ->
                  m.Id :: (bpsGrid |> List.map (fun b -> be |> List.find (fun r -> r.ModeId = m.Id && r.Bps = b && r.Balance = 250000.0) |> fun r -> r.Loaded |> Option.map money |> Option.defaultValue "never"))))
          ""
          "## 2b. Per-account licence pricing: accounts needed to break even (vendor cost only, 5 sponsors)"
          ""
          table [ "Mode"; "$40/acct"; "$81/acct (Ren software reference)"; "$120/acct"; "$150/acct"; "$250/acct" ]
              (allEconomics inputs vals |> List.filter (fun m -> m.Mode.Id = "MD-6" || m.Mode.Id = "MD-7" || m.Mode.Id = "MD-5")
                  |> List.map (fun m ->
                      m.Mode.Id :: ([ 40.0; 81.0; 120.0; 150.0; 250.0 ] |> List.map (fun price ->
                          let margin = price - m.VendorVariablePerAcct
                          if margin <= 0.0 then "never" else fmt (round ((m.VendorFixed + 5.0 * m.VendorSponsorLevelCost) / margin)) + " accts"))))
          ""
          "## 3. Break-even by balance (base; 5 sponsors)"
          ""
          table [ "Mode"; "Balance"; "5"; "10"; "15"; "20"; "25"; "30" ]
              [ for m in inputs.Modes do
                  for b in balances do
                      yield m.Id :: money b :: (bpsGrid |> List.map (fun bps -> be |> List.find (fun r -> r.ModeId = m.Id && r.Bps = bps && r.Balance = b) |> fun r -> r.Assets |> Option.map money |> Option.defaultValue "never")) ]
          ""
          "## 4. Monte Carlo break-even (P10 / P50 / P90; balance and sponsors sampled). Independent draws and correlated draws (rho 0.5: half of parameters share one adverse quantile)"
          ""
          table [ "Mode"; "bps"; "P10"; "P50"; "P90"; "Never covers variable cost"; "Corr P10"; "Corr P50"; "Corr P90"; "Corr never" ]
              (List.zip mc mcc |> List.map (fun (r, c) -> [ r.ModeId; fmt r.Bps; money r.P10; money r.P50; money r.P90; pct r.NeverShare; money c.P10; money c.P50; money c.P90; pct c.NeverShare ]))
          ""
          "## 4a. Correlated pessimistic stress at 20 bps (AI factor 0.88; touches x1.5; minutes x1.3; no automation failure benefit; fixed cost x1.15)"
          ""
          table [ "Mode"; "Base break-even"; "Stress break-even"; "Base min/acct"; "Stress min/acct" ]
              (st |> List.map (fun r -> [ r.ModeId; money r.BaseAssets; money r.StressAssets; n2 r.BaseMinutes; n2 r.StressMinutes ]))
          ""
          "## 5. Where the conventional-to-AI-native saving comes from (event cost per account-year)"
          ""
          table [ "Step"; "From"; "To"; "Saving $/acct"; "Minutes saved/acct" ]
              (dec |> List.map (fun d -> [ d.Step; d.FromMode; d.ToMode; n2 d.SavingPerAcct; n2 d.MinutesSaved ]))
          ""
          "## 6. Prevention versus faster processing (MD-5, $ per account-year)"
          ""
          table [ "Event"; "Prevention mechanism"; "Value of prevention"; "Value of AI speed" ]
              (prev |> List.filter (fun p -> p.PreventionValue > 0.005 || p.SpeedValue > 0.005) |> List.sortByDescending (fun p -> p.PreventionValue + p.SpeedValue)
                    |> List.map (fun p -> [ p.EventId + " " + p.Name; p.Prevention; n2 p.PreventionValue; n2 p.SpeedValue ]))
          ""
          "## 7. Event Pareto (per-account cost incl. pass-through and sponsor-level share at 10k accounts / 5 sponsors)"
          ""
          table [ "Mode"; "Event"; "$/acct"; "Share"; "Cumulative" ]
              ((par1 |> List.truncate 8) @ (par5 |> List.truncate 8) |> List.map (fun r -> [ r.ModeId; r.EventId + " " + r.Name; n2 r.CostPerAcct; pct r.Share; pct r.Cumulative ]))
          ""
          "## 8. Tornado: break-even assets at 20 bps (MD-5 and MD-6)"
          ""
          table [ "Mode"; "Parameter"; "Low → break-even"; "High → break-even" ]
              (tor |> List.filter (fun t -> t.Swing > 0.0) |> List.map (fun t -> [ t.ModeId; t.Param; fmt t.LowValue + " → " + money t.AtLow; fmt t.HighValue + " → " + money t.AtHigh ]))
          ""
          "## 9. Registry: reconstruction of the $316k estimate"
          ""
          table [ "Component"; "Annual (base)"; "Classification"; "Removable when" ]
              ((fst regRecon |> List.map (fun (c, x) -> [ c.Id + " " + c.Name; money x; c.Classification; c.RemovableWhen ])) @ [ [ "**Total**"; money (snd regRecon); ""; "" ] ])
          ""
          "## 10. Registry alternatives (20k charities per sponsor, 1 sponsor, 4% change rate, change-driven, 70k grants)"
          ""
          table [ "Alternative"; "Run cost"; "Per grant"; "Human hours"; "Establishment"; "MC P10"; "MC P50"; "MC P90" ]
              (regBase |> List.map (fun (name, r) ->
                  let p10, p50, p90 = regMc |> List.find (fun (id, _) -> id = r.AltId) |> snd
                  [ r.AltId + " " + name; money r.Total; n2 r.PerGrant; fmt (round r.HumanHours); money r.Establishment; money p10; money p50; money p90 ]))
          ""
          "## 11. Registry: lowest run cost per sponsor by population and refresh policy (4% change rate)"
          ""
          table [ "Charities/sponsor"; "Sponsors"; "Refresh"; "Cheapest alternative"; "Run cost"; "Per sponsor"; "Per grant" ]
              (lowest |> List.map (fun r -> [ fmt r.Charities; fmt r.Sponsors; r.Refresh; r.Alt; money r.Result.Total; money r.Result.PerSponsor; n2 r.Result.PerGrant ]))
          ""
          "## 12. Entry routes: capital (deepest cumulative deficit over 120 months; 8% churn; go-live lag)"
          ""
          table [ "Route"; "Case"; "Capital"; "First cash-positive month"; "Payback month (cumulative >= 0)"; "Cumulative at 60"; "Cumulative at 120"; "Live customers at 60"; "Annual revenue at 60" ]
              (routes |> List.map (fun r ->
                  [ r.RouteId; r.Case; money r.Result.Capital; (match r.Result.FirstPositiveMonth with Some m -> string m | None -> "none in 120")
                    (match r.Result.PaybackMonth with Some m -> string m | None -> "none in 120"); money r.Result.CumulativeAt60; money r.Result.CumulativeAt120; n2 r.Result.CustomersAt60; money r.Result.AnnualRevenueAt60 ]))
          ""
          table [ "Route"; "rho"; "Capital P10"; "P50"; "P90"; "No payback within 120 months"; "Payback month P50" ]
              (routeMc |> List.map (fun r -> [ r.RouteId; fmt r.Rho; money r.P10; money r.P50; money r.P90; pct r.NoPayback120; n2 r.PaybackP50 ]))
          "" ]
    String.concat "\n" sections
